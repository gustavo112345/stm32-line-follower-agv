#include <drivers/hw_system_clock.h>

void SystemClock_Init(void) {

    //CONFIG GPIO CLOCK
    RCC->AHB1ENR |= (RCC_AHB1ENR_GPIOBEN | RCC_AHB1ENR_GPIOAEN);

    //CONFIG SYSTEM CLOCK=100MHZ
    RCC->CR |= RCC_CR_HSEON;  // HSE ENABLE
    while(!(RCC->CR & RCC_CR_HSERDY));

    RCC->PLLCFGR &= ~(RCC_PLLCFGR_PLLM_Msk); // CLEAR PLLM
    RCC->PLLCFGR |= (13U << RCC_PLLCFGR_PLLM_Pos);  // SET M=13; fVCO_in = 1.92MHZ

    RCC->PLLCFGR &= ~(RCC_PLLCFGR_PLLN_Msk); // CLEAR PLLN
    RCC->PLLCFGR |= (104U << RCC_PLLCFGR_PLLN_Pos); //SET N=104; fVCO_out = 200MHZ

    RCC->PLLCFGR &= ~(RCC_PLLCFGR_PLLP_Msk); // CLEAR PLLP
    RCC->PLLCFGR |= (0U << RCC_PLLCFGR_PLLP_Pos);// SET P=2; SYSCLK=100MHZ

    RCC->PLLCFGR |= RCC_PLLCFGR_PLLSRC_HSE; // HSI TO HSE

    FLASH->ACR &= ~(FLASH_ACR_LATENCY_Msk | FLASH_ACR_DCEN | FLASH_ACR_ICEN | FLASH_ACR_PRFTEN);
    FLASH->ACR |= ((3U << FLASH_ACR_LATENCY_Pos) | FLASH_ACR_DCEN | FLASH_ACR_ICEN | FLASH_ACR_PRFTEN);
    while((FLASH->ACR & FLASH_ACR_LATENCY_Msk) != FLASH_ACR_LATENCY_3WS);

    RCC->CR |= RCC_CR_PLLON; // PLL ENABLE
    while(!(RCC->CR & RCC_CR_PLLRDY));

    RCC->CFGR &= ~(RCC_CFGR_PPRE1_Msk); //LIMPAR BITS PPRE1
    RCC->CFGR |= (RCC_CFGR_PPRE1_DIV2);  // AHB DIVIDIDO POR 2 f_APB1=50MHZ

    RCC->CFGR &= ~(RCC_CFGR_SW_Msk); //LIMPAR OS BITS
    RCC->CFGR |= (RCC_CFGR_SW_PLL); // PLL SELECTED SYSCLK
    while((RCC->CFGR & RCC_CFGR_SWS_Msk) != RCC_CFGR_SWS_PLL);

    SystemCoreClock = 100000000UL;
}
